export const BUILDING_LIST = Object.values(BUILDINGS);

export function getBuildingSpec(typeId) {
  return BUILDINGS[typeId] || null;
}

export function getBuildingTierSpec(typeId, tier = 1, evolutionId = null) {
  const b = BUILDINGS[typeId];
  if (!b) return null;
  if (evolutionId && b.evolutions) {
    const evo = b.evolutions.find((e) => e.id === evolutionId);
    if (evo) return { ...b.tiers[b.tiers.length - 1], ...evo, isEvolution: true };
  }
  const idx = Math.max(0, Math.min(b.tiers.length - 1, tier - 1));
  return b.tiers[idx];
}
